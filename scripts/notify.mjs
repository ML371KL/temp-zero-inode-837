// Идемпотентность: база сравнения двигается ОДИН раз в конце прогона, а список уже доставленных
// сообщений пишется после КАЖДОЙ отправки. Поэтому падение Telegram на середине рассылки не
// приводит ни к потере хвоста (база осталась старой — события пересчитаются), ни к повтору
// начала (эти ключи уже в индексе). Ключ включает сами значения: то же событие с другими
// числами — это новое событие. У смены доли и сигнала риска ключ несёт ещё и дату (сессию смены
// или время снимка): индекс защищает только от ПОВТОРА того же прогона, а не от настоящего
// повторения того же перехода через три дня.
const SENT_TTL_MS = 7 * 24 * 3600 * 1000;
const sentKey = (ev) => `${ev.key}|${ev.before}→${ev.after}|${(ev.moves || []).map((m) => m.after).join(",")}`;

// Память о показанных значениях переписанных точек: ключ «карточка|метка времени» → значения,
// о которых уже сообщалось. Нужна, чтобы отличить настоящий пересмотр от качка источника
// туда-обратно. Живёт дольше индекса доставленного: качок может вернуться и через месяц.
const REVISED_TTL_MS = 90 * 24 * 3600 * 1000;
const REVISED_MAX_VALUES = 6;

function rememberRevised(prev, events, now) {
  const out = {};
  for (const [k, rec] of Object.entries(prev || {})) {
    const at = Date.parse(rec?.at || "");
    if (Number.isFinite(at) && now - at < REVISED_TTL_MS && Array.isArray(rec.v)) out[k] = { v: rec.v.slice(), at: rec.at };
  }
  for (const ev of events) {
    for (const p of ev.revisedPoints || []) {
      const k = `${p.id}|${p.t}`;
      const rec = (out[k] = out[k] || { v: [], at: new Date(now).toISOString() });
      // Помним ОБЕ стороны показанного пересмотра: качок возвращает точку именно к прежнему
      // значению, то есть к «было», а не к «стало» — на этом первая версия фильтра и промахнулась.
      for (const v of [p.before, p.after]) {
        if (finite(v) && !rec.v.some((x) => sameNum(x, v))) rec.v.push(v);
      }
      if (rec.v.length > REVISED_MAX_VALUES) rec.v = rec.v.slice(-REVISED_MAX_VALUES);
      rec.at = new Date(now).toISOString();
    }
  }
  return out;
}

function pruneSent(sent, now) {
  const out = {};
  for (const [k, iso] of Object.entries(sent || {})) {
    const t = Date.parse(iso);
    if (Number.isFinite(t) && now - t < SENT_TTL_MS) out[k] = iso;
  }
  return out;
}

// prev — прошлая база: официальное закрытие, которое в этом прогоне не прочиталось (close === null),
// переносится из неё — иначе следующее закрытие сравнивать было бы не с чем.
function snapshotState(panel, prev = null) {
  const indicators = {};
  for (const i of panel.indicators || []) {
    const close = i.close !== undefined ? (i.close ? { d: i.close.d, v: i.close.v } : prev?.indicators?.[i.id]?.close || null) : undefined;
    indicators[i.id] = {
      ...(close !== undefined ? { close } : {}),
      value: i.value,
      value_num: i.value_num,
      unit: i.unit,
      zone: i.zone,
      score: i.score,
      observed_at: i.observed_at,
      degraded: !!i.degraded,
      points: i.points || null,
    };
  }
  const detectors = {};
  for (const d of panel.detectors || []) detectors[d.id] = { state: d.state };
  return {
    version: 1,
    updated_at: new Date().toISOString(),
    generated_at: panel.generated_at || "",
    verdict: { word: panel.verdict?.word || "" },
    allocation: panel.allocation || null,
    indicators,
    detectors,
    revisions: panel.revisions || [],
    // поставщики данных этого прогона — база для providersSwitched (смена источника ≠ пересмотр)
    ...(panel.providers ? { providers: panel.providers } : {}),
    // версия страницы — смена методики ≠ пересмотр (см. diff); нет в этом прогоне — помним прежнюю
    ...(panel.page_version || prev?.page_version ? { page_version: panel.page_version || prev.page_version } : {}),
  };
}

// Ряд решений копится САМИМ уведомлением: панели публикуют только текущее состояние, а для
// «часто ли такое откатывается» нужна собственная история. 400 наблюдений — это примерно две
// недели часового такта и месяц с лишним у макро-панели.
const TREND_MAX = 400;
// Журнал СМЕН доли живёт отдельно и дольше ряда наблюдений: смены редки (единицы в месяц), и
// подрезать их вместе с почасовыми точками — значит навсегда лишиться базы частот откатов.
const CHANGES_MAX = 200;
function appendChanges(prev, panel, prevAlloc) {
  const rows = [...(prev || [])];
  const cur = panel.allocation;
  // Каноническая ступень ведёт журнал смен в ветке `ledger`; здесь копится только переходная
  // (старая полоса), и лестницы разных версий в одну запись не смешиваются.
  if (cur?.canonical || prevAlloc?.canonical) return rows.slice(-CHANGES_MAX);
  if (cur && finite(cur.pct) && prevAlloc && finite(prevAlloc.pct) && !sameNum(prevAlloc.pct, cur.pct)) {
    rows.push({ t: Date.parse(panel.generated_at || "") || Date.now(), from: prevAlloc.pct, to: cur.pct });
  }
  return rows.slice(-CHANGES_MAX);
}
function appendTrend(prev, panel) {
  const sample = panel.allocation?.sample || (panel.allocation && finite(panel.allocation.pct)
    ? { t: Date.parse(panel.generated_at || "") || Date.now(), pct: panel.allocation.pct, score: panel.allocation.score ?? null }
    : null);
  if (!sample) return prev || [];
  const rows = (prev || []).filter((x) => finite(x?.t) && x.t < sample.t);
  rows.push(sample);
  return rows.slice(-TREND_MAX);
}

// Проверка связи: убедиться, что токен и chat_id верные, не дожидаясь первого настоящего
// изменения. Состояние НЕ трогает — после пинга обычный ход рассылки не сбивается.
function pingMessage(panel) {
  const det = (panel.detectors || []).filter((d) => d.state !== "calm");
  return [
    "✅ <b>Проверка связи</b>",
    "Бот подключён, уведомления настроены.",
    "",
    `Сейчас на панели: <b>${esc(panel.verdict?.word || "—")}</b>`,
    panel.verdict?.extra ? esc(panel.verdict.extra) : "",
    panel.allocation && finite(panel.allocation.pct)
      ? `Доля ${panel.assetWord || "рискового актива"} сейчас: <b>${panel.allocation.pct}%</b>${panel.allocation.canonical ? " стратегической нормы" : ""}`
      : "",
    ownerText(panel.allocation),
    `Показателей под наблюдением: ${(panel.indicators || []).length}`,
    det.length ? `Детекторы не в покое: ${esc(det.map((d) => `${d.name} (${DET_LABEL[d.state] || d.state})`).join(", "))}` : "Все детекторы спокойны",
  ]
    .filter(Boolean)
    .join("\n");
}

// io — швы для прогона без браузера, сети и диска (тесты, воспроизведение на истории снимков):
//   panel      — готовая проекция панели вместо чтения страницы (см. fromPageRaw);
//   ledger     — прошлый журнал решений вместо файла NOTIFY_LEDGER_IN (null — «ветки ещё нет»);
//   saveLedger — куда отдать новую версию журнала вместо файла NOTIFY_LEDGER_OUT;
//   snapshot   — снимок для запасных закрытий S&P и фондов вместо docs/snapshot.json;
//   state      — состояние прошлого запуска вместо файла (null — «состояния нет»);
//   saveState  — куда отдать состояние вместо записи файла;
//   deliver    — получатель готового сообщения вместо Telegram и NEXUS. С ним прогон идёт БОЕВОЙ
//                веткой (индекс доставленного, запись состояния после каждой отправки), но ни
//                токен, ни сеть не нужны.
// В бою main() вызывается без аргументов.
async function main(io = {}) {
  const ping = process.env.NOTIFY_PING === "1" && !io.panel;
  // Файл прошлого прогона не должен уехать в ветку шагом коммита ЭТОГО прогона: новая версия
  // журнала появляется заново только тогда, когда этот прогон её действительно построил.
  if (!ping && !io.saveLedger) await rm(LEDGER_OUT, { force: true });
  const prevLedger = io.ledger !== undefined ? io.ledger : await readLedger(LEDGER_IN);
  const panel = io.panel || (await readPanel({ writer: { memory: validMemory(prevLedger?.memory) ? prevLedger.memory : null } }));

  let ledgerNext = null;
  let ledgerDirty = false;
  if (panel.source === "page") {
    // Время снимка и закрытие S&P страница обычно отдаёт сама; локальный снимок — запасной путь.
    const day = panel.decision?.dataAsOf;
    const fundsGap = Object.keys(DIARY_FUNDS).some((k) => closeOn(panel.fund_points?.[k], day) === null);
    const snap = !panel.snapshot_at || closeOn(panel.spx_points, day) === null || fundsGap
      ? (io.panel ? io.snapshot ?? null : await readJSON(PAGE_DIR ? join(PAGE_DIR, "snapshot.json") : SNAPSHOT_PATH))
      : null;
    panel.snapshot_at = panel.snapshot_at || snap?.generated_at || "";
    const spx = closeOn(panel.spx_points, day) ?? closeOn(snapshotSpx(snap), day);
    const funds = fundClosesOn(panel.fund_points, snapshotFunds(snap), day);
    ({ ledger: ledgerNext, changed: ledgerDirty } = canonicalize(panel, prevLedger, { snapshotAt: panel.snapshot_at, spx, funds }));
    const d = panel.decision;
    if (d) console.log(`решение страницы: ${d.regimeWord || d.regime || "—"} · ступень ${d.rung} (${d.pct}%) · сырая ${d.raw} · данные на ${d.dataAsOf || "—"} · источник ${d.source || "—"} · прошлая ступень журнала ${validMemory(prevLedger?.memory) ? prevLedger.memory.rung : "нет (первый прогон)"}`);
  }

  if (ping) {
    // Проверка связи проверяет ВСЮ цепочку, включая комментатор: без этого его отказ было не
    // увидеть до первого настоящего события, и он молча простоял в шаблоне весь первый день.
    // Живая карточка панели берётся как повод, чтобы прогнать модель на реальных данных.
    const sample = (panel.indicators || []).find((i) => HUMAN[i.id] && i.value && !HUMAN[i.id].quiet);
    let verdictLine = "Комментатор: ключ не задан, сообщения будут без разбора";
    if (process.env.ANTHROPIC_API_KEY && sample) {
      const probe = [{
        kind: "release",
        title: releaseOf(sample),
        before: "",
        after: "",
        detail: "",
        moves: [{ name: humanTitle(sample.id, sample.name), before: fmtValue(sample), after: fmtValue(sample), delta: "" }],
        plain: humanPlain(sample.id) ? [`${humanTitle(sample.id, sample.name)} — ${humanPlain(sample.id)}`] : [],
        history: historyDigest(sample) ? [`${humanTitle(sample.id, sample.name)}: ${historyDigest(sample)}`] : [],
        note: "",
      }];
      // Пинг делает один настоящий запрос: его usage и цену печатает строкой «Claude: …» сам
      // транспорт. Суточный потолок к пингу не применяется — диагностика обязана дойти до модели,
      // — и в состояние пинг ничего не пишет; расход за сегодня из состояния печатается для сверки.
      const spend = spendOf((await readJSON(STATE_PATH))?.llm_spend);
      console.log(`расход на Claude за ${mskDay()} МСК: $${spentToday(spend).toFixed(4)} при потолке $${llmDailyCap()}`);
      const got = await llmComments(probe, panel);
      // Пинг — диагностический режим, поэтому текст разбора печатается и в лог: иначе оценить
      // качество ответа можно только по Telegram, а это неудобно при отладке.
      if (got?.[0]) console.log(`пример разбора (${LAST_MODEL}):\n${got[0]}`);
      verdictLine = got?.[0]
        ? `Комментатор работает (${LAST_MODEL || resolveModel()}). Пример разбора:\n<i>${esc(got[0].slice(0, 600))}</i>`
        : `Комментатор НЕ ответил (${resolveModel()}) — сообщения пойдут без разбора, причина в логе прогона`;
    }
    const text = `${pingMessage(panel)}\n\n${verdictLine}`;
    if (DRY) console.log(text.replace(/<[^>]+>/g, ""));
    else await sendTelegram(text); // обрезку под предел Telegram делает сам транспорт
    console.log(DRY ? "пинг: dry-run, ничего не отправлено" : "пинг отправлен");
    return;
  }

  // Журнал пишется ДО рассылки: каноническая ступень сайта не должна зависеть от здоровья
  // Telegram. Сообщение о смене при этом не теряется — его база (state.allocation) сдвигается
  // только после удачной рассылки, см. canonicalBase.
  if (ledgerNext && ledgerDirty) {
    if (io.saveLedger) await io.saveLedger(ledgerNext);
    else {
      await mkdir(dirname(LEDGER_OUT), { recursive: true });
      await writeFile(LEDGER_OUT, formatLedger(ledgerNext));
    }
    console.log(`журнал решений: ступень ${ledgerNext.memory.rung}, смен ${ledgerNext.transitions.length}, дневник ${ledgerNext.diary.length} сес. → ${io.saveLedger ? "io" : LEDGER_OUT}`);
  } else if (ledgerNext) {
    console.log("журнал решений: существенных изменений нет — коммита в ветку не будет");
  }

  const prev = io.state !== undefined ? io.state || {} : (await readJSON(STATE_PATH)) || {};
  const dry = io.deliver ? false : DRY;
  const first = !prev.indicators;
  const now = Date.now();
  const sentIndex = pruneSent(prev.sent, now);
  let revisedSeen = prev.revised_points || {};
  // Прошлый журнал — второй источник базы для канонической доли (первый — объявленная ступень).
  const all = first ? [] : diff({ ...prev, ledger: prevLedger }, panel);
  const events = all.filter((ev) => !sentIndex[sentKey(ev)]);

  if (first) console.log("первый прогон: зафиксирована база, уведомления начнутся со следующего изменения");
  if (all.length !== events.length) console.log(`уже доставлено ранее и пропущено: ${all.length - events.length}`);
  console.log(`событий: ${events.length}`);

  // Осторожный режим: тесты уведомлений в этом прогоне не прошли (исход шага передаёт notify.yml).
  // Раньше красный тест останавливал весь прогон — и все сообщения, включая смену доли, и запись журнала
  // решений, единственным писателем которого этот скрипт и является. Теперь журнал пишется как обычно
  // (выше, до рассылки), смена доли и сигналы риска идут — их мало, и ключ каждого привязан к моменту
  // события; публикации и пересмотры, где ошибка кода способна дать лавину, не рассылаются, а о самом сбое
  // раз в сутки приходит служебное сообщение. Без состояния оно не шлётся: помнить «уже сказано» нечем.
  let queue = events;
  let selftestAlertAt = prev.selftest_alert_at || "";
  if ((io.selftest ?? process.env.NOTIFY_SELFTEST) === "failure") {
    queue = events.filter((ev) => SAFE_KINDS.has(ev.kind));
    console.log(`тесты уведомлений не прошли — осторожный режим: публикаций и пересмотров не разослано ${events.length - queue.length}`);
    const lastAt = Date.parse(selftestAlertAt);
    if (!first && !(finite(lastAt) && now - lastAt < SELFTEST_ALERT_EVERY_MS)) {
      selftestAlertAt = new Date(now).toISOString();
      queue = [{
        kind: "service",
        key: `selftest@${selftestAlertAt}`,
        title: "Тесты уведомлений не проходят",
        before: "",
        after: "",
        detail: "Идут только сообщения о смене доли и сигналы риска. Публикации и пересмотры данных не рассылаются, пока тесты не починены. Журнал решений пишется как обычно. Причина — в журнале прогона «Уведомления в Telegram».",
        note: "",
      }, ...queue];
    }
  }

  const trend = appendTrend(prev.alloc_trend, panel);
  const allocChanges = appendChanges(prev.alloc_changes, panel, prev.allocation);
  let baseline = null; // сдвигается один раз в самом конце — до тех пор пишем старую базу
  let ruleNotesSeen = { ...(prev.rule_notes || {}) };   // v5.4: пояснения к правилу, уже доставленные
  // Расход на разбор за московские сутки копится в состоянии и переживает прогоны: с ним каждый
  // запрос сверяется с потолком NOTIFY_LLM_DAILY_USD. Объект один на прогон — транспорт дописывает
  // в него цену ответа, persist() уносит на диск.
  const llmSpend = spendOf(prev.llm_spend);
  // Недельный учёт разборов и отказов API (блок 5б): поле llm_week, строка раз в неделю и тревога о
  // доступе уходят в канал ошибок в конце прогона.
  const llmWeek = prev.llm_week && typeof prev.llm_week === "object" && !Array.isArray(prev.llm_week) ? prev.llm_week : {};
  const persist = async () => {
    const state = { ...(baseline || prev), sent: sentIndex, revised_points: revisedSeen, alloc_trend: trend, alloc_changes: allocChanges, rule_notes: ruleNotesSeen, llm_spend: llmSpend, llm_week: llmWeek };
    if (selftestAlertAt) state.selftest_alert_at = selftestAlertAt;
    if (io.saveState) return io.saveState(state);
    await mkdir(dirname(STATE_PATH), { recursive: true });
    await writeFile(STATE_PATH, JSON.stringify(state, null, 1));
  };

  let sent = 0;
  if (queue.length) {
    const capped = queue.slice(0, MAX_EVENTS);
    if (queue.length > MAX_EVENTS) console.log(`ПРЕДОХРАНИТЕЛЬ: событий ${queue.length} > ${MAX_EVENTS}, отправляются первые ${MAX_EVENTS} по важности`);
    // Разбор нужен не всем событиям: служебному сообщению модель не нужна.
    const ask = capped.map((ev, idx) => ({ ev, idx })).filter((x) => !NO_COMMENT.has(x.ev.kind));
    const got = ask.length ? await llmComments(ask.map((x) => x.ev), panel, { spend: llmSpend, week: llmWeek }) : null;
    const llm = got ? new Array(capped.length).fill(null) : null;
    if (got) ask.forEach((x, k) => { llm[x.idx] = got[k] || null; });
    // Оплаченный запрос — на диск сразу, до рассылки: упавший на Telegram прогон не должен
    // стереть его из суточного расхода. База сравнения при этом не двигается (baseline ещё null).
    await persist();
    console.log(`комментарии: ${llm ? `модель (${LAST_MODEL || resolveModel()})` : "шаблон"}`);
    for (let i = 0; i < capped.length; i++) {
      const ev = capped[i];
      const comment = (llm && llm[i]) || templateComment(ev);
      const text = renderMessage(ev, comment);
      if (dry) {
        const plain = text
          .replace(/<[^>]+>/g, "")
          .replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&");
        console.log("\n--- сообщение " + (i + 1) + " ---\n" + plain);
      } else {
        if (io.deliver) await io.deliver(text, ev);
        else {
          await sendTelegram(text);
          await sendNexusEvent(text, sentKey(ev), panel.generated_at);
        }
        console.log(`  → отправлено: ${KIND[ev.kind]?.label || ev.kind} · ${ev.title}${ev.before || ev.after ? ` (${ev.before || "—"} → ${ev.after || "—"})` : ""} · комментарий: ${llm && llm[i] ? "модель" : "шаблон"}`);
        sent++;
        sentIndex[sentKey(ev)] = new Date().toISOString();
        if (ev.revisedPoints) revisedSeen = rememberRevised(revisedSeen, [ev], now);
        for (const id of ev.ruleNotes || []) ruleNotesSeen = { ...ruleNotesSeen, [id]: new Date().toISOString() };
        await persist(); // индекс доставленного — сразу на диск, база сдвинется в конце
        if (i < capped.length - 1 && !io.deliver) await sleep(SEND_GAP_MS);
      }
    }
  }

  if (dry) revisedSeen = rememberRevised(revisedSeen, queue.filter((e) => e.revisedPoints), now);
  baseline = snapshotState(panel, prev);
  await persist();
  console.log(dry ? "dry-run: ничего не отправлено, база сравнения обновлена" : `отправлено сообщений: ${sent}`);
  // Учёт ИИ-разборов (блок 5б): тревога при отказе API по доступу и строка за прошлую неделю — в канал
  // ошибок. Каждым прогоном: неделя без событий — тоже неделя, а недоставленное уйдёт следующим.
  // Сухой прогон и прогон через io.deliver (тесты, реплей) в канал ошибок не пишут; тесты подставляют io.sendOps.
  const sendOps = io.sendOps || (dry || io.deliver ? null : guardSendOps);
  if (sendOps) {
    const out = await guardOpsTick(llmWeek, now, "837", sendOps, "секрет ANTHROPIC_API_KEY в настройках репозитория (Actions).");
    if (out.length) {
      console.log(`канал ошибок: ${out.join("; ")}`);
      await persist();
    }
  }
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith("notify.mjs")) {
  main().catch((e) => {
    console.error("notify упал:", e);
    process.exit(1);
  });
}

