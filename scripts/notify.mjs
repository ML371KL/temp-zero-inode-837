function pendingRuleNotes(prevState, nowMs = Date.now()) {
  const seen = (prevState && prevState.rule_notes) || {};
  const day = new Date(nowMs).toISOString().slice(0, 10);
  return RULE_NOTES.filter((n) => !seen[n.id] && day >= n.from && day <= n.until);
}

